<#
.SYNOPSIS
Independent check that every settable Kiota request-body member is either bound by a cmdlet
parameter or accounted for by a named policy.

.DESCRIPTION
Compilation proves that what we DO emit has the right CLR type - a wrong type name cannot
build. It cannot see what we FAIL to emit: a settable model member with no parameter, or a
parameter declared and never assigned, are both perfectly valid C#. This closes that gap.

The invariant, per request-body model:

    settable kiota members == parameters with assignments
                            + properties excluded by a named policy
                            + properties reported as an unsupported shape

Nothing here re-derives classification from the OpenAPI spec. The three inputs are produced
independently of each other:

  * the kiota client   - generated by kiota, parsed here for its settable members and the
                         serialized (OpenAPI) name each one deserializes from
  * the emitted cmdlet - parsed here for [Parameter] declarations and body.X = Y assignments
  * the generator log  - the classifier's own per-property exclusion/unsupported diagnostics

A disagreement between them is a real defect in one of the three, which is the point.

Failures reported:
  MISSING           a settable member with no parameter and no cited policy
  NO-ASSIGNMENT     a parameter that never assigns to the body
  WRONG-TARGET      an assignment to a member the model does not have
  NO-PARAMETER      an assignment reading an undeclared parameter
  DUPLICATE         two parameters assigning the same member
  UNCITED           a property excluded citing an unrecognised policy or shape
  NO-MODEL          a body type with no generated model file to check against
  GENERATOR-FAILED  generation failed, so its diagnostics cannot be trusted

Modules whose spec or build output is absent are reported as skipped and counted, so a run
cannot look complete while silently covering less than it was asked to.

.PARAMETER Module
Modules to check. Default: every module with generated cmdlets under -OutputRoot.

.EXAMPLE
.\tools\Test-BodyBindingCoverage.ps1 -Module Users
.EXAMPLE
.\tools\Test-BodyBindingCoverage.ps1
#>
[CmdletBinding()]
param(
    [string[]]$Module,
    [string]$OutputRoot,
    [ValidateSet('v1.0', 'beta')]
    [string]$ApiVersion = 'v1.0',
    [string]$SpecRoot
)

$ErrorActionPreference = 'Stop'
$repoRoot = (Resolve-Path (Join-Path $PSScriptRoot '..')).Path
if (-not $OutputRoot) { $OutputRoot = Join-Path $repoRoot 'artifacts\wrapper-modules' }
if (-not $SpecRoot) { $SpecRoot = Join-Path $repoRoot 'openApiDocs_KiotaCompat' }
$OutputRoot = (Resolve-Path -LiteralPath $OutputRoot).Path
$generator = Join-Path $repoRoot 'tools\WrapperGenerator'

if (-not $Module) {
    $Module = @(Get-ChildItem $OutputRoot -Directory |
        Where-Object { Test-Path (Join-Path $_.FullName 'src\Cmdlets') } |
        ForEach-Object { $_.Name } | Sort-Object)
}
if (-not $Module) { Write-Error "No modules found under '$OutputRoot'."; exit 2 }

# --- kiota model members -----------------------------------------------------------------
# The deserializer map is the authority for which OpenAPI name feeds which member:
#     { "displayName", n => { DisplayName = n.GetStringValue(); } },
# Reading it avoids re-deriving kiota's name-cleaning rules (underscores, Prop suffixing)
# here, which would just be a second implementation that could drift from the first.
$deserializerEntry = '\{\s*"(?<json>[^"]+)"\s*,\s*n\s*=>\s*\{\s*(?<member>\w+)\s*='

# Members are inherited: Message declares Subject but gets ChangeKey from OutlookItem and
# CreatedDateTime from Entity, each in its own file with its own deserializer map. Walking the
# base chain is required or every inherited assignment looks like it targets a member that does
# not exist.
# relativeName is everything after ".Models." - "CallRecords.Participant", not "Participant".
# Kiota nests a dotted schema name as a sub-namespace and a sub-folder, and several of those
# nested models share a simple name with a different model at the root
# (Models/Participant.cs vs Models/CallRecords/Participant.cs). Matching on the simple name
# silently compares a cmdlet against the wrong model, which is worse than not finding one.
function Get-ModelMembers([string]$modelsDir, [string]$relativeName, [System.Collections.Generic.HashSet[string]]$visited) {
    if ($null -eq $visited) { $visited = [System.Collections.Generic.HashSet[string]]::new() }
    if (-not $visited.Add($relativeName)) { return @{} }   # defensive: never loop on a cyclic chain

    $segments = $relativeName -split '\.'
    $typeName = $segments[-1]
    $file = Join-Path $modelsDir ((($segments) -join [IO.Path]::DirectorySeparatorChar) + '.cs')
    if (-not (Test-Path $file)) { return $null }
    $text = Get-Content $file -Raw
    $folder = if ($segments.Count -gt 1) { ($segments[0..($segments.Count - 2)] -join '.') + '.' } else { '' }

    $map = @{}
    # The base type is fully qualified in the declaration; keep whatever sits after ".Models."
    # so a nested base resolves to its own folder rather than the root.
    $baseMatch = [regex]::Match($text, "public partial class $([regex]::Escape($typeName))\s*:\s*global::[A-Za-z0-9_.]*?\.Models\.(?<base>[A-Za-z0-9_.]+)\s*,")
    if ($baseMatch.Success) {
        $inherited = Get-ModelMembers $modelsDir $baseMatch.Groups['base'].Value $visited
        if ($null -ne $inherited) {
            foreach ($k in $inherited.Keys) { $map[$k] = $inherited[$k] }
        }
    }
    foreach ($m in [regex]::Matches($text, $deserializerEntry)) {
        $map[$m.Groups['member'].Value] = $m.Groups['json'].Value
    }
    return $map
}

# --- run the generator once per module to collect its diagnostics --------------------------
$results = [System.Collections.Generic.List[object]]::new()
$failures = [System.Collections.Generic.List[object]]::new()

# Only these may account for an unbound member. An exclusion naming anything else means the
# generator emitted a policy this check does not know about, which must fail rather than be
# accepted as a citation.
$knownPolicies = @(
    'ServerAssignedId', 'ODataControlData', 'KiotaAdditionalData', 'ReadOnlySchema', 'NavigationProperty'
)
$knownShapes = @('InlineEnum', 'UnknownFormat', 'InlineObject', 'Union', 'Dictionary', 'Unresolvable')

$skipped = [System.Collections.Generic.List[string]]::new()

foreach ($name in $Module) {
    $spec = Join-Path $SpecRoot "$ApiVersion\$name.yml"
    if (-not (Test-Path $spec)) { $spec = Join-Path $repoRoot "openApiDocs\$ApiVersion\$name.yml" }
    if (-not (Test-Path $spec)) { $skipped.Add("$name (no spec)"); continue }

    $cmdletsDir = Join-Path $OutputRoot "$name\src\Cmdlets"
    $modelsDir = Join-Path $OutputRoot "$name\src\Client\Models"
    if (-not (Test-Path $cmdletsDir) -or -not (Test-Path $modelsDir)) { $skipped.Add("$name (not built)"); continue }

    $log = & dotnet run --project $generator -c Release -- `
        -d $spec -o (Join-Path $env:TEMP "binding-oracle-$name") -n "Microsoft.Graph.PowerShell.$name.Client" `
        --api-version $ApiVersion --log-level Information 2>&1
    # A failed generation produces no diagnostics, which would make every unbound member look
    # like an uncited omission - or worse, make a module with no cmdlets look clean.
    if ($LASTEXITCODE -ne 0) {
        $failures.Add([pscustomobject]@{ Module = $name; Cmdlet = '(generation)'; Kind = 'GENERATOR-FAILED'; Detail = "exit $LASTEXITCODE; diagnostics unusable" })
        continue
    }

    # noun -> set of OpenAPI property names the classifier deliberately did not bind.
    # The two diagnostics are parsed separately and validated against DIFFERENT vocabularies: a
    # policy exclusion and an unsupported shape are different claims, and one accepted set would
    # let "Excluded ...: Untyped" or "Unbound ...: ServerAssignedId" pass as a citation.
    $accounted = @{}
    foreach ($line in $log) {
        $kind = $null
        $m = [regex]::Match("$line", 'Excluded body property (?<noun>[^.]+)\.(?<prop>\S+): (?<reason>\S+)')
        if ($m.Success) { $kind = 'Excluded'; $allowed = $knownPolicies }
        else {
            $m = [regex]::Match("$line", 'Unbound body property (?<noun>[^.]+)\.(?<prop>\S+): (?<reason>\S+)')
            if ($m.Success) { $kind = 'Unbound'; $allowed = $knownShapes }
        }
        if (-not $kind) { continue }

        $reason = $m.Groups['reason'].Value.Trim()
        if ($reason -notin $allowed) {
            $expected = if ($kind -eq 'Excluded') { 'an ExclusionPolicy' } else { 'an UnsupportedShape' }
            $failures.Add([pscustomobject]@{ Module = $name; Cmdlet = '(diagnostics)'; Kind = 'UNCITED'; Detail = "$kind $($m.Groups['prop'].Value) cited '$reason'; expected $expected" })
            continue
        }
        $noun = $m.Groups['noun'].Value
        if (-not $accounted.ContainsKey($noun)) { $accounted[$noun] = [System.Collections.Generic.HashSet[string]]::new() }
        [void]$accounted[$noun].Add($m.Groups['prop'].Value)
    }

    foreach ($file in Get-ChildItem $cmdletsDir -Filter '*.g.cs' -File) {
        if ($file.Name -notmatch '^(New|Update)Mg') { continue }
        $text = Get-Content $file.FullName -Raw

        # -match populates $Matches; -notmatch does not, so each pattern is matched explicitly.
        $bodyMatch = [regex]::Match($text, 'var body = new ([A-Za-z0-9_.]+)\(\);')
        if (-not $bodyMatch.Success) { continue }
        $entityType = $bodyMatch.Groups[1].Value
        # Keep the sub-namespace: "...Models.CallRecords.Participant" -> "CallRecords.Participant".
        $modelsMarker = '.Models.'
        $markerAt = $entityType.IndexOf($modelsMarker)
        $relativeName = if ($markerAt -ge 0) { $entityType.Substring($markerAt + $modelsMarker.Length) } else { $entityType }
        $simpleName = $relativeName.Substring($relativeName.LastIndexOf('.') + 1)

        $members = Get-ModelMembers $modelsDir $relativeName $null
        if ($null -eq $members) {
            $failures.Add([pscustomobject]@{ Module = $name; Cmdlet = $file.BaseName; Kind = 'NO-MODEL'; Detail = "no generated model file for $relativeName" })
            continue
        }

        # The noun is used verbatim: the generator's diagnostics key on the same prefixed noun
        # (MgUserMailFolder), so stripping the prefix here would match nothing and report every
        # policy exclusion as an omission.
        $cmdletMatch = [regex]::Match($text, '\[Cmdlet\(Verbs\w+\.(\w+),\s*"([^"]+)"')
        if (-not $cmdletMatch.Success) { continue }
        $noun = $cmdletMatch.Groups[2].Value

        # emitted parameters and the member each one assigns
        $parameters = @([regex]::Matches($text, '(?m)^\s+public\s+[^\r\n]+?\s+(\w+)\s*\{\s*get;\s*set;\s*\}') |
            ForEach-Object { $_.Groups[1].Value })
        # A schema-less property is assigned in two steps, so the right-hand side of the
        # assignment is a local rather than the parameter:
        #     var untypedX = UntypedValue.From(X);
        #     if (untypedX is not null) body.X = untypedX;
        # Mapping the local back to its parameter keeps the assignment attributable; without it
        # the parameter looks unassigned and the local looks undeclared.
        $localToParam = @{}
        foreach ($c in [regex]::Matches($text, 'var\s+(?<local>\w+)\s*=\s*UntypedValue\.From\((?<param>\w+)\)')) {
            $localToParam[$c.Groups['local'].Value] = $c.Groups['param'].Value
        }

        $assignments = @{}
        $assignedParams = [System.Collections.Generic.HashSet[string]]::new()
        foreach ($a in [regex]::Matches($text, '(?m)^\s+body\.(?<member>\w+)\s*=\s*(?<param>\w+)')) {
            $member = $a.Groups['member'].Value
            $source = $a.Groups['param'].Value
            if ($localToParam.ContainsKey($source)) { $source = $localToParam[$source] }
            if ($assignments.ContainsKey($member)) {
                $failures.Add([pscustomobject]@{ Module = $name; Cmdlet = $file.BaseName; Kind = 'DUPLICATE'; Detail = "two parameters assign body.$member" })
            }
            $assignments[$member] = $source
            [void]$assignedParams.Add($source)
        }

        # A parameter that never reaches the body is silently inert: it binds, the user supplies
        # a value, and the request goes out without it. The compiler is perfectly happy with it.
        # Parameters that legitimately do not assign are identified by how they are emitted, not
        # by a list of names: a path id carries an "= string.Empty" initializer, a header param
        # is added to requestConfiguration.Headers, and AccessToken/Headers are the shared
        # plumbing every cmdlet declares.
        $pathParams = @([regex]::Matches($text, '(?m)^\s+public\s+string\s+(\w+)\s*\{\s*get;\s*set;\s*\}\s*=\s*string\.Empty;') |
            ForEach-Object { $_.Groups[1].Value })
        $headerParams = @([regex]::Matches($text, 'requestConfiguration\.Headers\.Add\("[^"]*",\s*(\w+)!') |
            ForEach-Object { $_.Groups[1].Value })
        $nonBody = [System.Collections.Generic.HashSet[string]]::new([string[]](@('AccessToken', 'Headers') + $pathParams + $headerParams))
        foreach ($p in $parameters) {
            if ($assignedParams.Contains($p) -or $nonBody.Contains($p)) { continue }
            $failures.Add([pscustomobject]@{ Module = $name; Cmdlet = $file.BaseName; Kind = 'NO-ASSIGNMENT'; Detail = "-$p is declared but never assigned to the body" })
        }

        foreach ($member in $assignments.Keys) {
            if (-not $members.ContainsKey($member)) {
                $failures.Add([pscustomobject]@{ Module = $name; Cmdlet = $file.BaseName; Kind = 'WRONG-TARGET'; Detail = "body.$member is not a member of $simpleName" })
            }
            elseif ($assignments[$member] -notin $parameters) {
                $failures.Add([pscustomobject]@{ Module = $name; Cmdlet = $file.BaseName; Kind = 'NO-PARAMETER'; Detail = "body.$member reads undeclared $($assignments[$member])" })
            }
        }

        # every settable member must be assigned, or named in the classifier's diagnostics
        # Plain assignment, not an if-expression: an empty HashSet returned through the pipeline
        # enumerates to nothing and the variable lands as $null.
        $cited = [System.Collections.Generic.HashSet[string]]::new()
        if ($accounted.ContainsKey($noun)) { $cited = $accounted[$noun] }
        foreach ($member in $members.Keys) {
            if ($assignments.ContainsKey($member)) { continue }
            if ($cited.Contains($members[$member])) { continue }
            $failures.Add([pscustomobject]@{ Module = $name; Cmdlet = $file.BaseName; Kind = 'MISSING'; Detail = "$simpleName.$member ('$($members[$member])') has no parameter and no cited policy" })
        }

        $results.Add([pscustomobject]@{ Module = $name; Cmdlet = $file.BaseName; Members = $members.Count; Assigned = $assignments.Count })
    }
    Write-Host ("{0,-32} cmdlets {1,5}   members {2,6}   assigned {3,6}" -f $name,
        @($results | Where-Object Module -eq $name).Count,
        (($results | Where-Object Module -eq $name | Measure-Object Members -Sum).Sum),
        (($results | Where-Object Module -eq $name | Measure-Object Assigned -Sum).Sum))
}

if ($results.Count -eq 0) { Write-Error 'No New/Update cmdlets were examined; the oracle proved nothing.'; exit 2 }

$examinedModules = @($results | Select-Object -ExpandProperty Module -Unique)
# A module with no New/Update cmdlets has nothing for this oracle to check. Naming those
# explicitly keeps the population reconcilable without the reader subtracting two numbers.
# Compared against an explicit name list: a -match against an empty collection yields an empty
# array, which is falsy, so the filter would silently select nothing.
$skippedNames = @($skipped | ForEach-Object { ($_ -split ' ')[0] })
$noBodyCmdlets = @($Module | Where-Object { $_ -notin $examinedModules -and $_ -notin $skippedNames })
""
"modules requested         : $($Module.Count)"
"modules examined          : $($examinedModules.Count)"
"modules with no New/Update: $($noBodyCmdlets.Count)$(if ($noBodyCmdlets.Count) { " -> $($noBodyCmdlets -join ', ')" })"
"modules skipped           : $($skipped.Count)$(if ($skipped.Count) { " -> $($skipped -join ', ')" })"
"cmdlets examined : $($results.Count)"
"model members    : $(($results | Measure-Object Members -Sum).Sum)"
"bound by a param : $(($results | Measure-Object Assigned -Sum).Sum)"
"failures         : $($failures.Count)"
if ($failures.Count -gt 0) {
    ""
    $failures | Group-Object Kind | Sort-Object Count -Descending | Select-Object Count, Name | Format-Table -AutoSize | Out-String -Width 60
    $failures | Select-Object -First 25 | Format-Table Module, Cmdlet, Kind, Detail -AutoSize | Out-String -Width 200
    exit 1
}
"binding coverage verified: every settable member is bound or cited."
exit 0
